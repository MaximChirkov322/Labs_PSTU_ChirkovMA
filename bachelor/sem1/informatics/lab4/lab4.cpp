#include <iostream>  // Подключение библиотеки для работы с потоками ввода-вывода
#include <clocale> // Подключение библиотеки для работы с локализацией
#include <stdlib.h> // Подключение библиотеки для работы с функцией rand()
using namespace std; // Использование стандартного пространства имен
int main() 
{
    setlocale(LC_ALL, "Russian"); // Установка локализации на русский язык
    int n, j = 0, f = 0, k = 0; // Объявление переменных: n - количество элементов, j - индекс поиска нуля, f - флажок (0 - False, 1 - True), k - количество элементов нового массива
    cout << "Введите количество элементов " << endl; // Вывод сообщения пользователю о необходимости ввести количество элементов
    cin >> n; // Ввод количества элементов пользователем
    int a[n]; // Объявление одномерного массива размером n
    int b[2 * n]; // Объявление нового массива с запасом места под добавляемые элементы (их не может быть больше n)
    for (int i = 0; i < n; i++) // Цикл для заполнения массива
    {
        a[i] = rand() % 10; // Заполнение массива случайными числами от 0 до 9
    }
    cout << "Полученный массив: " << endl; // Вывод сообщения о выводе массива
    for (int i = 0; i < n; i++) // Цикл для перебора элементов массива при выводе
    { 
        cout << a[i] << " "; // Вывод элемента массива через пробел
    } 
    cout << endl; 
    while (j < n && f == 0) // Цикл поиска первого нуля идёт, пока не перебраны все элементы и нуль не найден
    { 
        if (a[j] == 0) // Проверка, равен ли текущий элемент нулю
        { 
            f = 1; // Если да, то флажок становится True и поиск заканчивается
        } 
        else // Иначе ноль ещё не найден
        { 
            j++; // Переход к следующему элементу массива
        } 
    } 
    if (f == 1) // Если флажок True, то первый нуль найден и его индекс равен j
    { 
        for (int i = j; i < n - 1; i++) // Цикл сдвига элементов, стоящих после нуля, на одну позицию влево
        { 
            a[i] = a[i + 1]; // Перезаписываем текущий элемент следующим элементом
        } 
        n--; // Уменьшаем количество элементов массива на 1
    } 
    for (int i = 0; i < n; i++) // Цикл для перебора элементов массива при добавлении новых элементов
    { 
        b[k] = a[i]; // Переписываем текущий элемент в новый массив
        k++; // Увеличиваем количество элементов нового массива на 1
        if (a[i] % 2 == 0 && i > 0) // Проверка, является ли текущий элемент чётным и есть ли перед ним предыдущий элемент
        { 
            b[k] = a[i - 1] + 2; // Если да, то добавляем после него элемент со значением M[I-1]+2, то есть значение предыдущего элемента плюс 2
            k++; // Увеличиваем количество элементов нового массива на 1
        } 
    }
    cout << "Полученный массив: " << endl; // Вывод сообщения о выводе полученного массива
    for (int i = 0; i < k; i++) // Цикл для перебора элементов нового массива при выводе
    { 
        cout << b[i] << " "; // Вывод элемента нового массива через пробел
    } 
    return 0; // Возврат значения 0 для успешного завершения программы
} 
