#include <iostream>                                       // библиотека ввода-вывода
using namespace std;                                      // пространство имён std

const int LEN = 256;                                      // 255 символов и '\0'

void Gets(char *s)                                        // ввод строки с клавиатуры
{                                                         // начало функции
    cin.getline(s, LEN);                                  // чтение до 255 символов
}                                                         // конец функции

void printWord(const char *title, const char *s,          // вывод слова на экран
               int start, int len)                        // начало и длина слова
{                                                         // начало функции
    int k;                                                // номер символа слова
    cout << title << ": ";                                // вывод заголовка
    for (k = 0; k < len; k++)                             // перебираем символы слова
    {                                                     // начало цикла
        cout << s[start + k];                             // вывод одного символа
    }                                                     // конец цикла
    cout << endl;                                         // переход на новую строку
}                                                         // конец функции

int main()                                                // главная функция программы
{                                                         // начало главной функции
    char s[LEN];                                          // введённая строка
    int i = 0, start, len;                                // позиция, начало, длина
    int maxLen = 0, maxStart = 0;                         // данные самого длинного
    int minLen = LEN, minStart = 0;                       // данные самого короткого

    cout << "Введите текст (заканчивается точкой):" << endl;    // приглашение к вводу
    Gets(s);                                              // ввод строки
    while (s[i] != '.' && s[i] != '\0')                   // пока не конец текста
    {                                                     // начало цикла по тексту
        if (s[i] == ' ')                                  // пробел между словами
        {                                                 // начало ветви 'да'
            i++;                                          // пропускаем пробел
        }                                                 // конец ветви 'да'
        else                                              // начало слова
        {                                                 // начало ветви 'нет'
            start = i;                                    // запоминаем начало слова
            while (s[i] != ' ' && s[i] != '.' &&          // идём до конца слова
                   s[i] != '\0')                          // (пробел, '.', конец строки)
            {                                             // начало цикла по слову
                i++;                                      // следующий символ
            }                                             // конец цикла по слову
            len = i - start;                              // длина найденного слова
            if (len > maxLen)                             // новое самое длинное?
            {                                             // начало ветви 'да'
                maxLen = len;                             // запоминаем длину
                maxStart = start;                         // запоминаем начало
            }                                             // конец ветви 'да'
            if (len < minLen)                             // новое самое короткое?
            {                                             // начало ветви 'да'
                minLen = len;                             // запоминаем длину
                minStart = start;                         // запоминаем начало
            }                                             // конец ветви 'да'
        }                                                 // конец ветви 'нет'
    }                                                     // конец цикла по тексту
    if (maxLen == 0)                                      // слов в тексте нет?
    {                                                     // начало ветви 'да'
        cout << "Слов нет" << endl;                 // слов нет
    }                                                     // конец ветви 'да'
    else
    {                                                     // начало ветви 'нет'
        printWord("Самое длинное слово", s, maxStart, maxLen);   // самое длинное слово
        printWord("Самое короткое слово", s, minStart, minLen);  // самое короткое слово
    }                                                     // конец ветви 'нет'
    return 0;                                             // завершение программы
}                                                         // конец главной функции
