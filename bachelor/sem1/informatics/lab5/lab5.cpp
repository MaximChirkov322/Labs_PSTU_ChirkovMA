#include <iostream>                         // подключение библиотеки ввода-вывода
#include <iomanip>                          // подключение setw (ширина поля вывода)
using namespace std;                        // стандартное пространство имён

const int N = 6;                            // число строк массива
const int M = 4;                            // число столбцов массива

void rows(int a[][M], int r1, int r2)   // обмен местами строк r1 и r2
{                                           // начало функции
    int j;                                  // номер столбца
    int t;                                  // временная переменная для обмена
    for (j = 0; j < M; j++)                 // перебираем все столбцы
    {                                       // начало цикла
        t = a[r1][j];                       // запоминаем элемент строки r1
        a[r1][j] = a[r2][j];                // элемент строки r2 записываем в r1
        a[r2][j] = t;                       // запомненный элемент записываем в r2
    }                                       // конец цикла
}                                           // конец функции

void stolbec(int a[][M], int n)   // сортировка строк по 3-му столбцу
{                                           // начало функции
    int i;                                  // номер прохода
    int j;                                  // номер пары соседних строк
    for (i = 0; i < n - 1; i++)             // n - 1 проход
    {                                       // начало внешнего цикла
        for (j = 0; j < n - 1 - i; j++)     // перебор пар соседних строк
        {                                   // начало внутреннего цикла
            if (a[j][2] > a[j + 1][2])      // 3-й столбец имеет индекс 2
            {                               // начало ветви 'да'
                rows(a, j, j + 1);      // меняем строки j и j+1 местами
            }                               // конец ветви 'да'
        }                                   // конец внутреннего цикла
    }                                       // конец внешнего цикла
}                                           // конец функции

void printmassiv(int a[][M], int n)          // вывод массива на экран
{                                           // начало функции
    int i;                                  // номер строки
    int j;                                  // номер столбца
    for (i = 0; i < n; i++)                 // перебираем строки
    {                                       // начало внешнего цикла
        for (j = 0; j < M; j++)             // перебираем элементы строки
        {                                   // начало внутреннего цикла
            cout << setw(4) << a[i][j];     // вывод элемента, ширина поля 4
        }                                   // конец внутреннего цикла
        cout << endl;                       // переход на новую строку
    }                                       // конец внешнего цикла
}                                           // конец функции

int main()                                  // главная функция программы
{                                           // начало главной функции
    int a[N][M] = {                         // исходный массив 6 x 4
        { 5, 2, 9, 1 },                     // строка 1
        { 3, 8, 4, 7 },                     // строка 2
        { 6, 1, 7, 2 },                     // строка 3
        { 9, 5, 1, 3 },                     // строка 4
        { 2, 4, 6, 8 },                     // строка 5
        { 7, 3, 4, 5 }                      // строка 6
    };                                      // конец списка инициализации

    cout << "Исходный массив:" << endl;        // вывод заголовка
    printmassiv(a, N);                       // вывод исходного массива
    stolbec(a, N);                // сортировка по 3-му столбцу
    cout << "Отсортированный массив:" << endl;// вывод заголовка
    printmassiv(a, N);                       // вывод отсортированного массива
    return 0;                               // завершение программы
}                                           // конец главной функции
