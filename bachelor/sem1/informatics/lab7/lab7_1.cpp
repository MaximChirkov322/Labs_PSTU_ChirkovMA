#include <iostream>                           // подключение библиотеки ввода-вывода
using namespace std;                          // стандартное пространство имён

double add(double a, double b)                // сложение вещественных чисел
{                                             // начало функции
    double s;                                 // переменная для суммы
    s = a + b;                                // вычисление суммы
    return s;                                 // возврат суммы
}                                             // конец функции

void add(double z1[], double z2[], double z[])  // сложение комплексных чисел
{                                             // начало функции
    z[0] = z1[0] + z2[0];                     // сумма действительных частей
    z[1] = z1[1] + z2[1];                     // сумма мнимых частей
}                                             // конец функции

int main()                                    // главная функция программы
{                                             // начало главной функции
    double a = 3.5;                           // первое вещественное число
    double b = 2.25;                          // второе вещественное число
    double c = -1.2;                          // третье вещественное число
    double d = 0.7;                           // четвёртое вещественное число
    double r1;                                // результат первого сложения
    double r2;                                // результат второго сложения
    double z1[2] = {2, 3};                    // число 2 + 3i: [0] - re, [1] - im
    double z2[2] = {4, -5};                   // число 4 - 5i
    double z3[2] = {1.5, 2.5};                // число 1.5 + 2.5i
    double z4[2] = {-0.5, 1};                 // число -0.5 + 1i
    double w1[2];                             // результат сложения z1 и z2
    double w2[2];                             // результат сложения z3 и z4
    r1 = add(a, b);                           // вызов функции для вещественных чисел
    cout << a << " + " << b << " = " << r1 << endl;  // вывод результата
    r2 = add(c, d);                           // вызов функции для вещественных чисел
    cout << c << " + " << d << " = " << r2 << endl;  // вывод результата
    add(z1, z2, w1);                          // вызов функции для комплексных чисел
    cout << "z1 + z2 = " << w1[0] << " + (" << w1[1] << ")i" << endl;  // вывод
    add(z3, z4, w2);                          // вызов функции для комплексных чисел
    cout << "z3 + z4 = " << w2[0] << " + (" << w2[1] << ")i" << endl;  // вывод
    return 0;                                 // завершение программы
}                                             // конец главной функции
